from app.services.address import parse_address

CASES = [
 ("خیابان جمهوری، بین ولیعصر و حافظ، پاساژ شرکا، طبقه اول، واحد 30", "پاساژ شرکا", 1, "30"),
 ("خیابان جمهوری اسلامی، نرسیده به پل حافظ، نبش کوچه شهید هادی جوان دلاور، پاساژ خانه موبایل، طبقه ۵، واحد ۵۱۵", "پاساژ خانه موبایل", 5, "515"),
 ("خیابان فردوسی، نرسیده به میدان فردوسی، مرکز تجارت جهانی فردوسی، طبقه همکف، واحد ۴۵، پلاک ۴۷۹", "مرکز تجارت جهانی فردوسی", 0, "45"),
 ("خیابان جمهوری اسلامی، بین حافظ و مرتضی، پاساژ چارسو، طبقه منفی یک، واحد A۴۱", "پاساژ چارسو", -1, "A41"),
 ("خیابان جمهوری اسلامی، خیابان فردوسی، ساختمان پلاسکو، طبقه بالای همکف، روبروی پله برقی، پلاک ۱۵۵", "ساختمان پلاسکو", 1, None),
 ("خیابان لاله زار نو، روبروی کوچه امین زاده، پلاک 544", None, None, None),
]

def test_cases():
    for addr, mall, floor, unit in CASES:
        p = parse_address(addr)
        assert p.mall == mall, (addr, p)
        assert p.floor == floor, (addr, p)
        assert p.unit == unit, (addr, p)

def test_plaque():
    assert parse_address("خیابان لاله زار، پلاک ۱۵ و ۱۶").plaque.startswith("15")
